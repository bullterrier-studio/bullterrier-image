"""The developer commands on a source checkout: what is generated from the effects (the gallery pictures,
`docs/effects.md`, `fx.pyi`) and the files of a new effect (`new_effect`, from the template).

Everything about an effect is found by its name, in a layout that mirrors the package: its code in
`src/photo_fx/effects/<name>/`, its tests in `tests/effects/<name>/`, its example recipe in `examples/effects/` and its
gallery picture in `docs/gallery/`. `effect_files` is the one place that says so; everything else asks it. Effects carry
their own documentation (category, docstring, signature), so nothing here is written by hand and no effect needs a
shared file edited. The shared files (`docs/effects.md`, `fx.pyi`) are regenerated deliberately, once, at integration
(`photo-fx regenerate`), not on every branch: that is what keeps parallel work free of merge conflicts. These are
developer commands; they need a source checkout of photo-fx.
"""

import ast
import inspect
import keyword
import re
from collections.abc import Sequence
from pathlib import Path
from string import Template
from typing import NamedTuple

from . import fx, imageio
from .core import registry
from .matte import subject_matte
from .ops.resample import resize
from .recipe import load_recipe, render

CHECKOUT = Path(__file__).resolve().parents[2]  # src/photo_fx/gallery.py -> the source checkout photo-fx runs from

_SIDE = 480  # px, longest side of a gallery picture
_QUALITY = 82  # JPEG: small files, and these are thumbnails
_ANIMATION_MOMENT = 0.5  # an animated example is shown mid-clip: its first frame is usually the untouched photo


def render_effects_page() -> str:
    """The text of `docs/effects.md`: one table per category (in the order of `registry.CATEGORIES`, empty ones left
    out) with each effect's gallery picture, name, one-sentence summary, parameters with their defaults, and a link to
    its example recipe; below it, a table per effect of every parameter's type, unit, range, default and description,
    read from its parameter model. Reads only the effects, so the same effects always give the same page."""
    grouped = {category: names for category, names in registry.categories().items() if names}
    lines = [
        "# Effects",
        "",
        "Every effect, by category. Each picture is the effect's example recipe (linked in the last column) run on the",
        "demo photo. Below each category, every parameter of its effects: unit, range, default and what it does.",
        "`uv run photo-fx effects` prints the same documentation.",
        "",
        "Generated by `photo-fx regenerate` from the effects themselves: do not edit by hand.",
        "",
        " | ".join(f"[{category.capitalize()}](#{category})" for category in grouped),
    ]
    for category, names in grouped.items():
        lines += ["", f"## {category.capitalize()}", ""]
        lines += ["| Example | Effect | What it does | Parameters | Recipe |", "| --- | --- | --- | --- | --- |"]
        lines += [_row(name) for name in names]
        for name in names:
            lines += _parameter_table(name)
    return "\n".join(lines) + "\n"


class EffectFiles(NamedTuple):
    """Where everything about one effect lives in a source checkout, by its name."""

    package: Path  # src/photo_fx/effects/<name>/: its code, `__init__.py` and `effect.py`
    tests: Path  # tests/effects/<name>/test_<name>.py: its behaviour tests
    example: Path  # examples/effects/<name>.toml: the short recipe that shows it, rendered for its picture
    picture: Path  # docs/gallery/<name>.jpg: its gallery picture (JPEG, longest side 480 px), shown by docs/effects.md


def effect_files(name: str, *, checkout: Path = CHECKOUT) -> EffectFiles:
    """Where the files of an effect called `name` live in `checkout`, whether or not they exist (yet)."""
    return EffectFiles(
        package=_layout(checkout).effects / name,
        tests=checkout / "tests" / "effects" / name / f"test_{name}.py",
        example=checkout / "examples" / "effects" / f"{name}.toml",
        picture=checkout / "docs" / "gallery" / f"{name}.jpg",
    )


def render_gallery(only: Sequence[str] = (), force: bool = False, *, checkout: Path = CHECKOUT) -> list[str]:
    """Render the example recipe of each effect (all, or those named in `only`) on the demo photo into its gallery
    picture (see `effect_files`), longest side 480 px. Pictures that already exist are kept unless `force` is set, so
    nothing changes that does not need to. Returns the names rendered. `checkout` is the photo-fx source checkout whose
    example recipes, demo photo (`examples/photos/bullterrier.jpeg`) and pictures are used.

    Everything is checked before anything is rendered: an unknown name raises `ValueError` listing the effects, a
    missing example recipe or a `checkout` that is no source checkout `FileNotFoundError`. Example recipes that cut out
    the subject need Apple Vision (macOS).
    """
    names = _chosen(only, checkout)
    todo = [name for name in names if force or not effect_files(name, checkout=checkout).picture.exists()]
    if not todo:
        return []
    photo, matte = imageio.load(_layout(checkout).photo), None
    for name in todo:
        files = effect_files(name, checkout=checkout)
        recipe = load_recipe(files.example)
        if recipe.needs_matte and matte is None:
            matte = subject_matte(photo)  # once for all the recipes that need it
        picture = render(photo, recipe, matte, at=_ANIMATION_MOMENT)
        files.picture.parent.mkdir(parents=True, exist_ok=True)
        imageio.save(resize(picture, _SIDE), files.picture, quality=_QUALITY)
    return todo


def write_docs(only: Sequence[str] = (), force: bool = False, *, checkout: Path = CHECKOUT) -> list[Path]:
    """Write `docs/effects.md` and render the gallery pictures that are missing (or those in `only`, or all of them
    with `force`; see `render_gallery`), both in `checkout`. The page is written first, so it is up to date even where
    pictures cannot be rendered. Returns the files written."""
    _chosen(only, checkout)  # a bad name fails before anything is written
    page = _layout(checkout).page
    page.write_text(render_effects_page(), encoding="utf-8")
    rendered = render_gallery(only, force, checkout=checkout)
    return [page, *(effect_files(name, checkout=checkout).picture for name in rendered)]


def regenerate(*, checkout: Path = CHECKOUT) -> list[Path]:
    """The one integration step after effects were added or changed: write `src/photo_fx/fx.pyi` (for editors) in
    `checkout`, then `write_docs`. Returns the files written. Every effect's example recipe is checked first, so a
    checkout that lacks one gets `FileNotFoundError` and no file is written."""
    _chosen((), checkout)
    stub = _layout(checkout).stub
    stub.write_text(fx.stub_text(), encoding="utf-8")
    return [stub, *write_docs(checkout=checkout)]


def new_effect(name: str, category: str, *, checkout: Path = CHECKOUT) -> list[Path]:
    """Write the files of a new effect called `name`, in `category` (one of `registry.CATEGORIES`), into `checkout`,
    each made from the template in `src/photo_fx/effects/_template/` and placed where `effect_files` says: its package
    (`__init__.py`, and `effect.py` with a parameter model with one documented example field and a working effect),
    its tests (`test_<name>.py`) and its example recipe. Returns the files written, sorted.

    The effect is registered whenever photo_fx is imported, and as written it passes the contract tests and its own;
    replacing the example with the real effect is the author's part. Its gallery picture is rendered later, from its
    example recipe, by `photo-fx gallery --only <name>` (or at integration). Raises `ValueError`, writing nothing, when
    `name` is not a lowercase Python identifier (a letter, then letters, digits and _) or is a Python keyword, is a
    name the template's `effect.py` already uses (its imports) or one `fx` defines for itself (so `fx.<name>` would not
    be the effect), or the category is unknown; `FileExistsError` when an effect of that name exists, or any of its
    files; and `FileNotFoundError` when `checkout` holds no template.
    """
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or keyword.iskeyword(name):
        raise ValueError(
            f"{name!r} cannot name an effect: use lowercase letters, digits and _, starting with a letter, and no "
            f"Python keyword"
        )
    if category not in registry.CATEGORIES:
        raise ValueError(f"unknown category {category!r}; choose one of: {', '.join(registry.CATEGORIES)}")
    if name in registry.describe():
        raise FileExistsError(f"there is already an effect called {name!r}")
    layout, files = _layout(checkout), effect_files(name, checkout=checkout)
    for taken in files:
        if taken.exists():
            raise FileExistsError(f"{taken} already exists: choose another name")
    if not (layout.template / "effect.py.tmpl").is_file():
        raise FileNotFoundError(f"no effect template in {layout.template}: this needs a source checkout of photo-fx")
    if name in _names_in_the_template_effect(layout.template):
        raise ValueError(f"{name!r} cannot name an effect: the template's effect.py already uses {name!r} for itself")
    if name in _names_fx_defines():
        raise ValueError(
            f"{name!r} cannot name an effect: fx defines {name!r} for itself, so fx.{name} would not build the effect"
        )
    targets = {  # template file -> where its copy goes
        "__init__.py.tmpl": files.package / "__init__.py",
        "effect.py.tmpl": files.package / "effect.py",
        "test_effect.py.tmpl": files.tests,
        "example.toml.tmpl": files.example,
    }
    words = _words(name, category)
    for template, target in targets.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            Template((layout.template / template).read_text(encoding="utf-8")).substitute(words), encoding="utf-8"
        )
    return sorted(targets.values())


def _words(name: str, category: str) -> dict[str, str]:
    """What the template's placeholders stand for: $name, $Name (the name in CamelCase, for the model), $category."""
    return {"name": name, "Name": "".join(part.capitalize() for part in name.split("_")), "category": category}


def _names_in_the_template_effect(template: Path) -> set[str]:
    """The module-level names the template's effect.py binds for itself (its imports, mainly), read from the template,
    so the list follows the template: an effect of one of these names would replace it or be replaced by it."""
    placeholder = "zzplaceholder"  # stands in for the name, so the names made from it can be told apart
    source = Template((template / "effect.py.tmpl").read_text(encoding="utf-8")).substitute(
        _words(placeholder, registry.CATEGORIES[0])
    )
    names: set[str] = set()
    for node in ast.parse(source).body:
        if isinstance(node, ast.Import | ast.ImportFrom):
            names |= {(alias.asname or alias.name).split(".")[0] for alias in node.names}
        elif isinstance(node, ast.ClassDef | ast.FunctionDef):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names |= {target.id for target in node.targets if isinstance(target, ast.Name)}
    return {name for name in names if placeholder not in name.lower()}


def _names_fx_defines() -> set[str]:
    """The public names of the `fx` module itself: `fx.<name>` finds those before it would look for an effect."""
    return {name for name in vars(fx) if not name.startswith("_")}


class _Layout(NamedTuple):
    """Where the files shared by all effects live in a source checkout."""

    effects: Path  # src/photo_fx/effects, one folder per effect: its presence makes a folder a source checkout
    template: Path  # the files a new effect's folder is made from (string.Template: $name, $Name, $category)
    photo: Path  # the demo photo every example recipe is shown on
    page: Path  # docs/effects.md
    stub: Path  # fx.pyi, next to fx.py


def _layout(checkout: Path) -> _Layout:
    package = checkout / "src" / "photo_fx"
    return _Layout(
        effects=package / "effects",
        template=package / "effects" / "_template",
        photo=checkout / "examples" / "photos" / "bullterrier.jpeg",
        page=checkout / "docs" / "effects.md",
        stub=package / "fx.pyi",
    )


def _chosen(only: Sequence[str], checkout: Path) -> list[str]:
    """The effects to work on, checked: each is a known effect with its example recipe in `checkout`."""
    names = list(only) or sorted(registry.describe())
    for name in names:
        try:
            registry.get(name)
        except KeyError as error:
            raise ValueError(error.args[0]) from None
    if not _layout(checkout).effects.is_dir():
        raise FileNotFoundError(f"{checkout} has no src/photo_fx/effects: this needs a source checkout of photo-fx")
    missing = [
        str(path) for path in (effect_files(name, checkout=checkout).example for name in names) if not path.is_file()
    ]
    if missing:
        raise FileNotFoundError(f"no example recipe: add {', '.join(missing)}")
    return names


def _row(name: str) -> str:
    # fx's signature is the one a recipe author sees: without the image, and without `matte`, which the recipe supplies
    parameters = inspect.signature(getattr(fx, name)).parameters.values()
    files = effect_files(name)
    page_folder = CHECKOUT / "docs"  # links are relative to the page, docs/effects.md
    example = files.example.relative_to(page_folder, walk_up=True).as_posix()
    picture = files.picture.relative_to(page_folder, walk_up=True).as_posix()
    cells = [
        f'<img src="{picture}" width="160" alt="{name}">',
        f"`{name}`",
        registry.summary(name),
        " ".join(f"`{p.name}={p.default!r}`" for p in parameters) or "none",
        f"[{files.example.name}]({example})",
    ]
    return "| " + " | ".join(_cell(text) for text in cells) + " |"


def _parameter_table(name: str) -> list[str]:
    """The lines of an effect's parameter table (name, type, unit, range, default, description), under a heading of its
    own."""
    model = registry.parameters(name)
    lines = ["", f"### `{name}`", "", "| Parameter | Type | Unit | Range | Default | Description |"]
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for doc in model.fields_doc():
        cells = [f"`{doc.name}`", doc.type, doc.unit or "", doc.range, f"`{doc.default!r}`", doc.doc]
        lines.append("| " + " | ".join(_cell(text) for text in cells) + " |")
    return lines


def _cell(text: str) -> str:
    """Text that stays inside one table cell: on one line, and with `|` escaped (also inside code)."""
    return " ".join(text.split()).replace("|", "\\|")
