"""Build recipes in Python: `fx.<effect>(...)` makes a validated step.

    from photo_fx import Recipe, fx, ramp, render

    look = Recipe("neon-glitch", size=1024, steps=[
        fx.gradient_map(stops=["#12002b", "#ff2bd6", "#00f0ff"]),
        fx.fill("#000000").where("background"),            # only where the photo's background is
        fx.glitch(split=12, bands=8, seed=4),
        fx.glow(radius=26, amount=0.65).blend(0.8),      # mixed in at 80%
    ])
    image = render(photo, look)

Every effect listed by `photo-fx effects` is here under its own name, with its own parameters and documentation
(`help(fx.glitch)`). A misspelt parameter fails when the step is made, not when the photo is rendered. Parameters can
change over an animation: `fx.disperse(progress=ramp(0, 0.9, "gentle"))`.

`fx.pyi` lets editors complete effect names and parameters. After adding or changing an effect, regenerate it with
`uv run python -m photo_fx.fx > src/photo_fx/fx.pyi` (a test fails while it is out of date).
"""

import inspect
from collections.abc import Callable
from functools import cache

from . import effects
from .recipe import Step


def __getattr__(name: str) -> Callable[..., Step]:
    if name.startswith("_"):
        raise AttributeError(name)
    try:
        return _builder(name)
    except KeyError:
        raise AttributeError(f"fx has no effect {name!r}; available: {', '.join(sorted(effects.describe()))}") from None


def __dir__() -> list[str]:
    return sorted(effects.describe())


@cache
def _builder(name: str) -> Callable[..., Step]:
    """The function behind `fx.<name>`: takes the effect's parameters (not the image) and returns a Step."""
    function = effects.get(name)
    signature = inspect.signature(function)
    image_parameter = next(iter(signature.parameters))

    def build(*args, **params) -> Step:
        try:
            bound = signature.bind_partial(None, *args, **params)  # None stands in for the image
        except TypeError as error:
            raise TypeError(f"fx.{name}(): {error}") from None
        return Step(name, {k: v for k, v in bound.arguments.items() if k != image_parameter})

    build.__name__, build.__qualname__, build.__doc__ = name, f"fx.{name}", function.__doc__
    build.__signature__ = _public_signature(signature).replace(return_annotation="Step")
    return build


def _public_signature(signature: inspect.Signature) -> inspect.Signature:
    """An effect's signature without the image (the recipe supplies it) and without `matte` (it supplies that too)."""
    parameters = [p for p in list(signature.parameters.values())[1:] if p.name != "matte"]
    return signature.replace(parameters=parameters, return_annotation=inspect.Signature.empty)


def stub_text() -> str:
    """The text of `fx.pyi`: one typed, documented function per effect, for editors."""
    lines = ['"""Generated by `python -m photo_fx.fx`; do not edit by hand."""', "", "from .recipe import Step", ""]
    for name in sorted(effects.describe()):
        function = effects.get(name)
        lines.append(f"def {name}{_public_signature(inspect.signature(function))} -> Step:")
        doc = (inspect.getdoc(function) or "").replace("\\", "\\\\").replace('"""', "'''")
        lines += [f'    """{doc}"""', "    ...", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    print(stub_text(), end="")
